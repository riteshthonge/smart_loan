const express = require('express');
const cors = require('cors');
const helmet = require('helmet');
const cookies = require('cookie-parser');
const { auth, role } = require('./middleware/auth');
const { wrap } = require('./utils');
const c = require('./controllers/applicant');
const app = express();
const origin = process.env.FRONTEND_URL || 'http://localhost:5173';
app.use(helmet()); app.use(cors({ origin, credentials: true })); app.use(express.json({ limit: '100kb' })); app.use(cookies());
app.use('/api', (req, res, next) => { res.set('Cache-Control', 'no-store'); if (!['GET', 'HEAD', 'OPTIONS'].includes(req.method) && (req.get('origin') !== origin || req.get('x-requested-with') !== 'SmartLoan')) return res.status(403).json({ message: 'Invalid request origin or CSRF header.' }); next(); });
app.get('/api/health', (req, res) => res.json({ status: 'ok' }));
app.use('/api/auth', require('./routes/auth'));
app.use('/api', auth);
app.use('/api/applicant', role('APPLICANT'), require('./routes/applicant'));
app.use('/api/admin', role('ADMIN'), require('./routes/admin'));
app.use('/api/applications', require('./routes/applications'));
app.use('/api/loan-products', require('./routes/products'));
app.use('/api/documents', require('./routes/documents'));
app.get('/api/documents/:id', wrap(require('./controllers/applications').download));
app.get('/api/documents/:id/download', wrap(require('./controllers/applications').download));
app.get('/api/notifications', wrap(c.notifications)); app.patch('/api/notifications/:id/read', wrap(c.read));
app.get('/api/loans', role('APPLICANT'), wrap(c.loans)); app.get('/api/loans/:id/emi-schedule', role('APPLICANT'), wrap(c.schedule));
app.use((req, res) => res.status(404).json({ message: 'Endpoint not found.' }));
app.use((err, req, res, next) => { if (res.headersSent) return next(err); let status = err.status || 500; let message = err.message; if (err.code === 11000) { status = 409; message = 'This email or product already exists, or an administrator is already configured.'; } if (['ValidationError', 'CastError'].includes(err.name) || err.name === 'MulterError') { status = 400; message = err.code === 'LIMIT_FILE_SIZE' ? 'Each document must be 5 MB or smaller.' : err.name === 'CastError' ? 'Invalid resource identifier.' : err.message; } if (status >= 500) { console.error(err); message = 'The request could not be completed. Please try again.'; } res.status(status).json({ message }); });
module.exports = app;
